// =============================================================================
//  src/ui/nav.js — یک درِ باریک به مسیریابیِ تب‌ها
// =============================================================================
//
//  # چرا این فایل وجود دارد و `goTab` در main.js نیست
//
//  چون `main.js` خودش `ai.js` و `views/*` را import می‌کند. اگر آن‌ها هم برای
//  عوض‌کردن تب به `main.js` برگردند، یک حلقهٔ import می‌شود: در ESM حلقه خطا
//  نمی‌دهد، ولی هر چیزی که در لحظهٔ ارزیابیِ ماژول خوانده شود `undefined` است و
//  اشکالش دقیقاً وقتی بیرون می‌زند که ترتیبِ بوت را عوض کنی. اینجا `main.js`
//  مسیریاب را **ثبت** می‌کند و بقیه فقط صدا می‌زنند؛ هیچ‌کس به بالادست import
//  نمی‌کند.
//
//  # چرا انتقال پرسش به چت در JS است و نه در Rust
//
//  در موبایل، «از دستیار بپرسید» باید از مرزِ فرآیند رد شود: شیت توضیح و صفحهٔ
//  چت دو مقصدِ ناوبری‌اند و پرسش در `AiSession` صف می‌شود. در دسکتاپ هر دو در
//  همان یک صفحهٔ WebView زندگی می‌کنند، پس یک اسلاتِ ماژولی همان کار را با یک
//  رفت‌وبرگشتِ IPC کمتر می‌کند. حالتِ حقیقی — تاریخِ گفت‌وگو — همچنان فقط در
//  Rust است؛ این اسلات یک قصدِ گذراست، نه یک حالت.

/** مسیریابِ ثبت‌شده از سوی `main.js`. */
let router = null

/** پرسشی که منتظر است صفحهٔ چت باز شود و آن را بفرستد. */
let queued = null

/** `main.js` در بوت این را صدا می‌زند. */
export function setTabRouter(fn) {
  router = fn
}

/**
 * به یک تب می‌رود. اگر مسیریابی ثبت نشده باشد (هارنسِ تست) بی‌صدا رد می‌شود.
 *
 * @returns {boolean} آیا ناوبری واقعاً انجام شد.
 */
export function goToTab(tab) {
  if (!router) return false
  router(tab)
  return true
}

/**
 * پرسش را برای صفحهٔ چت می‌گذارد و به آن صفحه می‌رود.
 *
 * ترتیب اهمیت دارد: **اول** صف، بعد ناوبری. اگر برعکس بود، صفحهٔ چت در همان
 * فراخوانِ `renderTab` ساخته می‌شد، `__onShow` را می‌گرفت، صف را خالی می‌دید و
 * پرسش تا ناوبریِ بعدی معلق می‌ماند.
 */
export function askInChat(text) {
  const trimmed = String(text ?? '').trim()
  if (!trimmed) return false
  queued = trimmed
  return goToTab('chat')
}

/**
 * پرسشِ منتظر را برمی‌دارد و اسلات را خالی می‌کند.
 *
 * برداشتنی و نه خواندنی: صفحهٔ چت با هر بازدید `__onShow` می‌گیرد، و پرسشی که
 * پس از خوانده‌شدن سرِ جایش بماند در بازدید بعدی دوباره فرستاده می‌شد.
 */
export function consumeQueuedQuestion() {
  const text = queued
  queued = null
  return text
}

/** فقط برای تست: اسلات را پاک می‌کند تا یک تست به تستِ بعدی نشت نکند. */
export function resetNav() {
  router = null
  queued = null
}
